import type { EdPeField, PeItem, PeMatrix } from "./types";

function pe(
  id: string,
  field: EdPeField,
  label: string,
  normal: string,
  abnormal: string[],
  abnormalTemplate?: string,
): PeItem {
  return abnormalTemplate === undefined
    ? { id, field, label, normal, abnormal }
    : { id, field, label, normal, abnormal, abnormalTemplate };
}

/** 矩陣型所見：類型 × 部位（輸出見 pe-matrix.ts）。abnormal 另外可放不分部位的快選。 */
function peMatrix(
  id: string,
  field: EdPeField,
  label: string,
  normal: string,
  matrix: PeMatrix,
  abnormal: string[] = [],
  legacy: string[] = [],
): PeItem {
  return legacy.length > 0
    ? { id, field, label, normal, abnormal, matrix, legacy }
    : { id, field, label, normal, abnormal, matrix };
}

